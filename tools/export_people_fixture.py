#!/usr/bin/env python3
"""Turn demo-data/people.json into src/data/northstar-accounts.ts for the frontend.

Only allow-listed fields are copied. Passwords, hashes, salts, TOTP secrets,
usernames and emails never leave demo-data/, so a field added to the dataset
later cannot leak into the browser by accident.

Usage:
    python3 tools/export_people_fixture.py demo-data/people.json src/data/northstar-accounts.ts
"""
import json
import sys

INCIDENT_ID = "northstar"  # matches src/data/fixtures.ts

# dataset field -> Account field (shared/contracts.ts)
SAFE = {
    "employee_id": "id",
    "department": "department",
    "job_title": "jobTitle",
    "privileged_access": "privileged",
    "mfa_type": "mfa",
    "credential_in_leak": "inCredentialLeak",
    "used_by_attacker": "usedByAttacker",
    "account_status": "status",
    "last_login_utc": "lastLogin",
}


def main(src_path: str, out_path: str) -> None:
    data = json.load(open(src_path, encoding="utf-8"))
    if not data.get("synthetic"):
        sys.exit("Refusing: dataset is not marked synthetic.")
    rows = []
    for p in data["people"]:
        row = {"id": p["employee_id"], "incidentId": INCIDENT_ID, "version": 1,
               "name": f'{p["first_name"]} {p["last_name"]}'.strip()}
        row.update({dst: p[src] for src, dst in SAFE.items() if dst != "id"})
        rows.append(row)
    body = json.dumps(rows, indent=2, ensure_ascii=False)
    out = (
        "// GENERATED by tools/export_people_fixture.py from demo-data/people.json.\n"
        "// Synthetic data. Secrets are removed by an allow-list. Do not edit by hand.\n"
        "import type { Account } from '../../shared/contracts';\n\n"
        f"export const northstarAccounts: Account[] = {body};\n"
    )
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"{len(rows)} accounts written to {out_path} (secret fields dropped)")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
